def extract_locators(text):
    """Locators genuinely present in this chunk.

    Real judgment paragraph numbers ascend through the chunk in document order and
    sit close together. We keep only the longest ascending run with small gaps,
    which rejects footnote markers, article numbers and stray numerals.
    """
    locs = []

    # candidate paragraph markers, IN ORDER OF APPEARANCE
    cands = [int(m.group(1)) for m in
             re.finditer(r'(?:(?<=^)|(?<=\s))\[?(\d{1,3})\]?\s+(?=[A-Z])', text)
             if 1 <= int(m.group(1)) <= 400]

    # longest ascending run with gaps <= 3
    best, cur = [], []
    for n in cands:
        if cur and 0 < n - cur[-1] <= 3:
            cur.append(n)
        else:
            if len(cur) > len(best): best = cur
            cur = [n]
    if len(cur) > len(best): best = cur

    if len(best) >= 2:                       # need a real run, not one stray number
        lo, hi = best[0], best[-1]
        locs.append(f"paragraphs {lo}-{hi}" if lo != hi else f"paragraph {lo}")

    arts = re.findall(r'Article\s+(\d{1,3}(?:\(\d+\))?)', text)
    if arts:
        locs.append("Articles " + ", ".join(list(dict.fromkeys(arts))[:6]))

    return "; ".join(locs)

def build_tagged_text(c):
    """Prepend a short identity/locator tag to the chunk text, for embedding only."""
    parts = []
    if c.get('search_terms'): parts.append(str(c['search_terms']).strip())
    parts.append(str(c.get('source_title', '')).strip())
    if c.get('subfolder'):    parts.append(str(c['subfolder']).strip())
    if c.get('jurisdiction'): parts.append(str(c['jurisdiction']).strip())
    if c.get('date'):         parts.append(str(c['date'])[:10])
    loc = extract_locators(c['text'])
    if loc: parts.append(loc)
    tag = " | ".join(p for p in parts if p)
    return tag + "\n\n" + c['text']

