def build_ui():
    session = {"chat": ChatSession(verbose=False)}   # one live session, resettable

    def respond(message, history):
        if not message.strip():
            return "", history, sources_text(session["chat"])
        try:
            answer = session["chat"].ask(message)
        except Exception as e:
            answer = f"Something went wrong answering that: {e}"
        history = history + [
            {"role": "user", "content": message},
            {"role": "assistant", "content": answer},
        ]
        return "", history, sources_text(session["chat"])

    def sources_text(chat):
        seen, lines = set(), []
        for c in chat.pool:
            t = c["metadata"].get("source_title", "")
            if t and t not in seen:
                seen.add(t); lines.append(f"• {t}")
        return "**Sources in this conversation:**\n" + ("\n".join(lines) if lines else "_(none yet)_")

    def reset():
        session["chat"] = ChatSession(verbose=False)
        return [], "**Sources in this conversation:**\n_(none yet)_"

    with gr.Blocks(title="ISDS Research Assistant") as demo:
        gr.Markdown(
            "# ISDS Research Assistant\n"
            "Answers **only** from a curated corpus of intra-EU / UK investor-state "
            "dispute settlement sources, with citations. It quotes when quoting, hedges "
            "when inferring, and refuses when the sources don't support an answer.\n\n"
            "_Prototype — verify all outputs against primary sources before relying on them._"
        )
        chatbot = gr.Chatbot(height=460)   # <-- modern message format
        with gr.Row():
            box = gr.Textbox(placeholder="Ask about a case, treaty provision, or doctrine…",
                             scale=8, show_label=False)
            send = gr.Button("Send", variant="primary", scale=1)
        clear = gr.Button("New conversation", size="sm")
        sources_md = gr.Markdown("**Sources in this conversation:**\n_(none yet)_")

        box.submit(respond, [box, chatbot], [box, chatbot, sources_md])
        send.click(respond, [box, chatbot], [box, chatbot, sources_md])
        clear.click(reset, None, [chatbot, sources_md])

    return demo

