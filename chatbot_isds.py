import re

def check_extraction_quality(text, filename):
    """Return a list of warnings about possible extraction issues."""
    warnings = []

    # 1. Suspiciously short
    if len(text) < 1000:
        warnings.append(f"Very short text ({len(text)} chars)")

    # 2. Real broken-word check: look for patterns where a CAPITALIZED short fragment
    # is followed by a lowercase continuation that's not a real word on its own.
    # "Net herlands" matches; "The court" doesn't (both are real words).
    # We look for: capital letter + 2-4 lowercase + space + 4+ lowercase letters,
    # where the second part doesn't start a sentence.
    suspicious = re.findall(r'(?<=[a-z]) ([A-Z][a-z]{1,3}) ([a-z]{4,})', text)
    # Count only those where neither part is a common short word
    common_short = {'The', 'And', 'For', 'But', 'Not', 'All', 'Any', 'One', 'Two',
                    'New', 'Old', 'Mr', 'Ms', 'Dr', 'Lord', 'See'}
    real_suspicious = [s for s in suspicious if s[0] not in common_short]
    if len(real_suspicious) > 50:
        warnings.append(f"Possible broken capitalised words ({len(real_suspicious)} suspicious patterns)")

    # 3. Garbage character ratio
    alpha_chars = sum(1 for c in text if c.isalnum() or c.isspace() or c in '.,;:()-"\'/')
    if alpha_chars / max(len(text), 1) < 0.85:
        warnings.append(f"High proportion of non-text characters")

    # 4. Common English words missing
    common_words = ['the', 'and', 'of', 'to', 'in']
    found_common = sum(1 for w in common_words if f' {w} ' in text.lower())
    if found_common < 3:
        warnings.append(f"Few common English words detected")

    return warnings

