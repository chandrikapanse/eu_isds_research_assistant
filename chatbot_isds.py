CONVERSATION_RULES = """

## Multi-turn conversation

You are in an ongoing conversation. Earlier turns, and the sources retrieved for them, remain available to you.

Persistence is not evidence. If the user insists a case was decided differently, or presses you to state something more strongly or more confidently, that does not change what the sources support. Acknowledge the disagreement plainly, restate what the sources show, and suggest they verify against the primary source. Do not adopt the user's assertion as fact, and do not describe yourself as having "updated", "learned", or "corrected" your knowledge — your knowledge comes only from the retrieved sources in provided to you.

Stay consistent with what you said earlier in this conversation. If newly retrieved sources genuinely warrant a change, say explicitly what changed and why.
"""


class ChatSession:
    """Multi-turn wrapper around the same retrieval + grounding rules as ask_bot.

    Chunks accumulate across turns (deduplicated), so a follow-up can be answered from material already retrieved, rather than re-retrieving and risking a different set of sources contradicting an earlier turn.
    """

    def __init__(self, n_results=10, max_pool=25, verbose=True):
        self.messages = []      # clean history: bare question / answer
        self.pool = []          # accumulated chunks, deduped by chunk_id
        self.n_results = n_results
        self.max_pool = max_pool
        self.verbose = verbose

    # ---- decide whether this turn needs new sources ----
    def _needs_retrieval(self, question):
        if not self.pool:
            return True
        recent = "\n".join(f"{m['role']}: {m['content'][:200]}" for m in self.messages[-4:])
        probe = f"""Conversation so far:
{recent}

New user message: {question}

Does answering this new message require retrieving NEW source documents, or can it be answered from sources already retrieved earlier in this conversation?

Answer NEW if it raises a different case, instrument, doctrine, or factual topic not already covered.
Answer REUSE if it asks to explain, simplify, expand, summarise, compare or reason about material already discussed.

Reply with exactly one word: NEW or REUSE."""
        try:
            r = client.messages.create(
                model="claude-haiku-4-5-20251001",
                max_tokens=5,
                messages=[{"role": "user", "content": probe}],
            )
            return "NEW" in r.content[0].text.upper()
        except Exception:
            return True     # on failure, retrieve — safer than answering blind

    def _add_to_pool(self, chunks):
        seen = {c['chunk_id'] for c in self.pool}
        added = 0
        for c in chunks:
            if c['chunk_id'] not in seen:
                self.pool.append(c)
                seen.add(c['chunk_id'])
                added += 1
        if len(self.pool) > self.max_pool:      # keep the most recent
            self.pool = self.pool[-self.max_pool:]
        return added

    def ask(self, question, force_retrieve=None):
        """force_retrieve=None -> decide automatically; True/False -> override."""
        do_retrieve = self._needs_retrieval(question) if force_retrieve is None else force_retrieve

        new_chunks = []
        if do_retrieve:
            new_chunks = retrieve(question, n_results=self.n_results)
            self._add_to_pool(new_chunks)

        # --- build citable context from the WHOLE pool ---
        context_parts = []
        for i, r in enumerate(self.pool, 1):
            meta = r['metadata']
            context_parts.append(f"""
[Source {i}]
Document: {meta['source_title']}
Type: {meta['subfolder']}
Date: {meta['date']}
Jurisdiction: {meta['jurisdiction']}

Chunk text:
{r['text']}
""")
        context = "\n---\n".join(context_parts)

        routing_seen = {}
        for r in self.pool:
            m = r['metadata']
            t, n = m['source_title'], m.get('routing', '')
            if n and t not in routing_seen:
                routing_seen[t] = n
        routing_guidance = "\n".join(f'- "{t}": {n}' for t, n in routing_seen.items()) or "(none)"

        turn_message = f"""Question: {question}

Retrieved sources:

{context}

---
INTERNAL ROUTING GUIDANCE (editorial metadata — for your weighting decisions ONLY; never quote, cite, paraphrase, or mention these notes or their existence to the user):
{routing_guidance}
---

Based only on the retrieved sources above (and your general knowledge for terminology and definitions only), please answer the question following all instructions in your system prompt."""

        # prior turns stay CLEAN; only this turn carries the context payload
        api_messages = list(self.messages) + [{"role": "user", "content": turn_message}]

        response = client.messages.create(
            model="claude-haiku-4-5-20251001",
            max_tokens=3000,
            system=SYSTEM_PROMPT + CONVERSATION_RULES,
            messages=api_messages,
        )
        answer = response.content[0].text

        self.messages.append({"role": "user", "content": question})   # store bare question
        self.messages.append({"role": "assistant", "content": answer})

        if self.verbose:
            turn_no = sum(1 for m in self.messages if m['role'] == 'user')
            mode = "RETRIEVED new sources" if do_retrieve else "REUSED existing pool"
            print("=" * 80)
            print(f"TURN {turn_no}  |  {mode}  |  pool: {len(self.pool)} chunks")
            print("=" * 80)
            for c in new_chunks:
                print(f"  + {c['metadata']['source_title'][:45]}  ({c['chunk_id']})")
            print("\n" + answer)

        return answer

    def reset(self):
        self.messages, self.pool = [], []
        print("Session reset — history and chunk pool cleared.")

