# ---- New retrieve(): prepends identity to what the RERANKER reads ----
def retrieve(query, n_results=10, n_candidates=100, per_doc_cap=4):
    """
    Two-stage retrieval:
      1. Embedding search over the contextually-tagged index (wide candidate pool).
      2. Voyage cross-encoder reranks those candidates. The reranker reads the
         ORIGINAL chunk text, so we prepend each candidate's identity (search
         terms, title, type, jurisdiction) before scoring — otherwise it cannot
         tell which court a passage comes from.
      3. Return the top n_results, capped per document for diversity.
    Stored text and what the bot sees are unchanged; the identity prefix is used
    for scoring only.
    """
    # --- Stage 1: wide embedding search ---
    query_embedding = vo.embed(
        texts=[query], model="voyage-law-2", input_type="query"
    ).embeddings[0]
    raw = collection.query(
        query_embeddings=[query_embedding],
        n_results=n_candidates,
        include=['documents', 'metadatas', 'distances'],
    )
    candidates = []
    for i in range(len(raw['ids'][0])):
        candidates.append({
            'chunk_id': raw['ids'][0][i],
            'text': raw['documents'][0][i],
            'metadata': raw['metadatas'][0][i],
            'distance': raw['distances'][0][i],
        })

    # --- Build the identity-prefixed text the reranker will score ---
    def rerank_input(c):
        m = c['metadata']
        bits = [m.get('search_terms', ''), m.get('source_title', ''),
                m.get('subfolder', ''), m.get('jurisdiction', '')]
        ident = " | ".join(b for b in bits if b)
        return (ident + "\n\n" + c['text']) if ident else c['text']

    # --- Stage 2: rerank ---
    rr = vo.rerank(
        query=query,
        documents=[rerank_input(c) for c in candidates],
        model="rerank-2.5",
        top_k=len(candidates),
    )

    # --- Stage 3: take top n_results with a per-document cap ---
    final, per_doc = [], {}
    for item in rr.results:
        c = dict(candidates[item.index])
        c['rerank_score'] = item.relevance_score
        doc = c['metadata']['source_file']
        if per_doc.get(doc, 0) >= per_doc_cap:
            continue
        final.append(c)
        per_doc[doc] = per_doc.get(doc, 0) + 1
        if len(final) == n_results:
            break

    return final

